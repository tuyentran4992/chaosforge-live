async page => {
  const base = 'http://127.0.0.1:3000';
  const waitReady = async (tab) => tab.waitForSelector('.state-chip[data-state="idle"].is-on');
  const select = async (tab, name) => tab.evaluate((route) => { location.hash = `#/${route}`; }, name);
  const room = async (tab, value) => {
    await select(tab, 'deck');
    await tab.locator('#roomCode').fill(value);
    await tab.locator('#joinRoom').click();
    await tab.waitForFunction((code) => document.querySelector('#raidStatus').textContent === `CONNECTED TO ${code}`, value);
  };
  await page.goto(`${base}/#/stage`);
  await page.reload();
  await waitReady(page);
  await page.locator('#judgeCompile').click();
  if (await page.locator('#judgeError').isHidden()) throw new Error('Missing prompt validation');
  await page.locator('[data-tab="live"]').click();
  if (await page.locator('[data-tab="live"]').getAttribute('aria-selected') !== 'true') throw new Error('Tab selection missing');
  await page.locator('[data-tab="sim"]').click();
  const bareObs = await page.context().newPage();
  await bareObs.goto(`${base}/overlay.html`);
  await bareObs.locator('#obsWarning').waitFor({ state: 'visible' });
  await bareObs.close();
  await select(page, 'overlay');
  const displayedUrl = await page.locator('#obsUrl').innerText();
  if (!new URL(displayedUrl).searchParams.get('studio')) throw new Error('OBS URL is missing Studio ID');
  await select(page, 'stage');
  const obs = await page.context().newPage();
  await obs.goto(await page.locator('#view-stage a[href*="overlay.html"]').getAttribute('href'));
  if (await obs.locator('#obsWarning').isVisible()) throw new Error('Valid OBS link warned');
  await room(page, 'AB12');
  await page.locator('#cartGrid .cart').first().click();
  await obs.waitForSelector('.ov[data-state="active"]');
  await page.locator('#sendCart').click();
  await page.locator('#raidLog').getByText('No rival is connected; cartridge was not sent.').waitFor();
  const rival = await page.context().newPage();
  await rival.goto(`${base}/#/deck`);
  await waitReady(rival);
  await room(rival, 'AB12');
  await page.locator('#cartGrid .cart').nth(1).click();
  await obs.waitForFunction(() => document.querySelector('[data-name]').textContent === 'BOSS');
  await page.waitForTimeout(400);
  const beforeSend = await rival.locator('#queueNowName').innerText();
  if (beforeSend !== 'NO PATCH') throw new Error(`Rival deployed before send: ${beforeSend}`);
  await page.locator('#sendCart').click();
  await rival.locator('#raidLog').getByText('Cartridge received from rival.').waitFor();
  await page.locator('#raidLog').getByText('Cartridge sent to 1 rival connection(s).').waitFor();
  if (await rival.locator('#queueNowName').innerText() !== 'BOSS') throw new Error('Rival deployment failed');
  await select(page, 'stage');
  await page.locator('#startVoteBtn').click();
  await page.waitForFunction(() => document.querySelector('#stageOverlay [data-poll]')?.children.length === 3);
  const before = await page.locator('#stageOverlay [data-countdown]').innerText();
  await page.waitForTimeout(1300);
  const after = await page.locator('#stageOverlay [data-countdown]').innerText();
  if (Number(after) >= Number(before)) throw new Error(`Countdown did not advance: ${before} to ${after}`);
  const late = await page.context().newPage();
  await late.goto(await page.locator('#view-stage a[href*="overlay.html"]').getAttribute('href'));
  await late.waitForSelector('.ov[data-state="voting"]');
  await late.waitForFunction(() => document.querySelector('[data-poll]').children.length === 3);
  await late.close();
  await obs.close();
  await rival.close();
  return { promptValidation: true, tabSelected: true, obsLink: true, beforeSend,
    received: 'BOSS', countdown: [before, after], lateJoin: 'voting' };
}
